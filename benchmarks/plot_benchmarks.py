import argparse
import csv
import os
from collections import defaultdict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


def _load_rows(csv_path: str, override_variant: str | None = None):
    rows = []
    with open(csv_path, "r", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            if not row.get("dataset_size"):
                continue
            variant = override_variant or row.get("variant") or "default"
            rows.append({
                "name": row["name"],
                "dataset_size": int(row["dataset_size"]),
                "latency_ms": float(row["latency_ms"]),
                "variant": variant,
            })
    return rows


def _split_by_index_and_variant(rows):
    groups = defaultdict(lambda: defaultdict(list))
    for row in rows:
        name = row["name"]
        variant = row["variant"]
        if "FlatIndex_Search" in name:
            groups[variant]["FlatIndex"].append(row)
        elif "HnswIndex_Search" in name:
            groups[variant]["HnswIndex"].append(row)
        elif "YdbIndex_Search" in name:
            groups[variant]["YdbIndex"].append(row)
    for variant_groups in groups.values():
        for group in variant_groups.values():
            group.sort(key=lambda r: r["dataset_size"])
    return groups


def _plot_latency(groups, output_dir):
    plt.figure(figsize=(7, 4.5))
    for variant, variant_groups in groups.items():
        for label, rows in variant_groups.items():
            sizes = [r["dataset_size"] for r in rows]
            latencies = [r["latency_ms"] for r in rows]
            plt.plot(sizes, latencies, marker="o", label=f"{label} ({variant})")

    plt.xscale("log")
    plt.yscale("log")
    plt.xlabel("Dataset size (N)")
    plt.ylabel("Latency (ms)")
    plt.title("Latency vs Dataset Size")
    plt.grid(True, which="both", linestyle="--", linewidth=0.5)
    plt.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, "latency_vs_dataset.png"), dpi=160)
    plt.close()


def _plot_speedup(groups, output_dir):
    plt.figure(figsize=(7, 4.5))
    plotted = False
    for variant, variant_groups in groups.items():
        flat = {row["dataset_size"]: row["latency_ms"] for row in variant_groups.get("FlatIndex", [])}
        hnsw = {row["dataset_size"]: row["latency_ms"] for row in variant_groups.get("HnswIndex", [])}
        common_sizes = sorted(set(flat.keys()) & set(hnsw.keys()))
        if not common_sizes:
            continue

        speedup = [flat[size] / hnsw[size] for size in common_sizes]
        plt.plot(common_sizes, speedup, marker="s", label=variant)
        plotted = True

    if not plotted:
        plt.close()
        return

    plt.axhline(1.0, color="red", linestyle="--", linewidth=1.0)
    plt.xscale("log")
    plt.xlabel("Dataset size (N)")
    plt.ylabel("Speedup (Flat / HNSW)")
    plt.title("HNSW Speedup over FlatIndex")
    plt.grid(True, which="both", linestyle="--", linewidth=0.5)
    plt.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, "speedup_ratio.png"), dpi=160)
    plt.close()


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot benchmark CSV results.")
    parser.add_argument("input_csv", nargs="?", help="CSV file generated by benchmark_to_csv.py")
    parser.add_argument("output_dir", nargs="?", help="Directory for PNG graphs")
    parser.add_argument("--output-dir", dest="output_dir_opt", help="Directory for PNG graphs")
    parser.add_argument("--inputs", nargs="+", help="Multiple CSV files to plot together")
    parser.add_argument("--labels", nargs="+", help="Variant labels for --inputs (same length)")
    args = parser.parse_args()

    output_dir = args.output_dir_opt or args.output_dir
    if not output_dir:
        raise ValueError("Provide output directory via positional output_dir or --output-dir")

    os.makedirs(output_dir, exist_ok=True)

    rows = []
    if args.inputs:
        if args.labels and len(args.labels) != len(args.inputs):
            raise ValueError("--labels must match number of --inputs")
        for idx, csv_path in enumerate(args.inputs):
            label = args.labels[idx] if args.labels else None
            rows.extend(_load_rows(csv_path, override_variant=label))
    elif args.input_csv:
        rows = _load_rows(args.input_csv)
    else:
        raise ValueError("Provide input_csv or --inputs")

    groups = _split_by_index_and_variant(rows)

    if not groups:
        raise ValueError("No FlatIndex/HnswIndex entries found in CSV")

    _plot_latency(groups, output_dir)
    _plot_speedup(groups, output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
